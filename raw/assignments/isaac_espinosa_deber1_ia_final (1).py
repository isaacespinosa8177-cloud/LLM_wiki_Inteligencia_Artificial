def get_successors(state):
  blank = state.index(0)
  row=blank//3
  col=blank%3

  move_indexes= []
  if row >0:
    move_indexes.append(blank-3)
  if row <2:
    move_indexes.append(blank+3)
  if col >0:
    move_indexes.append(blank-1)
  if col <2:
    move_indexes.append(blank+1)

  successors=[]
  for new_index in move_indexes:
    new_state=list(state)
    new_state[blank]=state[new_index]
    new_state[new_index]=0
    successors.append(tuple(new_state))
  return successors

def bfs(start,goal):
  queue=[[start]]
  visited=set()
  visited.add(start)
  states_generated=1

  while len(queue)>0:
    path=queue.pop(0)
    current=path[-1]

    if current==goal:
      return path,states_generated

    successors=get_successors(current)
    for next_state in successors:
      if next_state not in visited:
        visited.add(next_state)
        states_generated=states_generated+1
        new_path=path+[next_state]
        queue.append(new_path)

  return None, states_generated

def dfs(start,goal,max_depth):
  stack=[[start]]
  visited=set()
  visited.add(start)
  states_generated=1

  while len(stack)>0:
    path=stack.pop()
    current=path[-1]

    if current==goal:
      return path,states_generated

    if len(path)-1<max_depth:
      successors=get_successors(current)
      for next_state in successors:
        if next_state not in visited:
          visited.add(next_state)
          states_generated=states_generated+1
          new_path=path +[next_state]
          stack.append(new_path)

  return None, states_generated

def get_position(value,state):
  index=state.index(value)
  row=index//3
  col=index%3
  return row,col

def manhattan_distance(state,goal):
  total=0
  value=1
  while value <= 8:
    row1,col1=get_position(value,state)
    row2,col2=get_position(value,goal)
    total=total+abs(row1-row2)+abs(col1-col2)
    value=value+1
  return total


def euclidean_distance(state,goal):
  total=0.0
  value=1
  while value <=8:
    row1,col1=get_position(value,state)
    row2,col2=get_position(value,goal)
    squared_distance=(row1-row2)**2 + (col1-col2)**2
    total=total+squared_distance ** 0.5
    value=value+1
  return total


