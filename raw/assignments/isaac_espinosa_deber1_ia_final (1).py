def validate(chessboard,row,column):
  for i in range (column):
    if chessboard[i]==row:
      return False

    if abs(chessboard[i]-row)==abs(i-column):
      return False

  return True

def solve(chessboard,column,n):
  if column==n:
    return True
  for row in range(n):
    if validate(chessboard,row,column):
      chessboard[column]=row
      if solve(chessboard,column+1,n):
        return True
  return False

