def heuristica_manhattan(tablero):

    total = 0

    for i, ficha in enumerate(tablero):

        if ficha is None:
            continue

        fila_actual = i // N
        col_actual = i % N

        fila_meta, col_meta = posicion_meta[ficha]

        total += (
            abs(fila_actual - fila_meta)
            + abs(col_actual - col_meta)
        )

    return total




